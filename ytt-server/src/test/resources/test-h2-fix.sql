-- ============================================================
-- H2 测试库修正脚本（仅在测试环境执行）
-- H2 不处理 SQL 字符串字面量中的反斜杠转义，V2 种子数据中第 10 题
-- options 内的 \" 被原样存为 \\"，导致 JacksonTypeHandler 解析 JSON 失败。
-- 此处将其替换回单反斜杠，与 MySQL 生产库实际存储保持一致。
-- ============================================================
UPDATE `question` SET `options` = REPLACE(`options`, '\\"', '\"') WHERE `id` = 10;
